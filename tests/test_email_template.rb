# frozen_string_literal: true

require_relative "test_helper"

class TestEmailTemplate < Minitest::Test
  DETAILS = {
    "NHC_STATUS" => "CRIT",
    "NHC_CHECK_COUNT" => "3",
    "NHC_CRIT" => "1",
    "NHC_WARN" => "0",
    "NHC_OK" => "2",
    "NHC_SKIP" => "0",
    "NHC_UNKNOWN" => "0",
    "NHC_FS_RO" => "CRIT",
    "NHC_FS_RO_MSG" => "read-only: /data (ext4)",
    "NHC_DATASTORE_MOUNTS" => "OK",
    "NHC_DATASTORE_MOUNTS_MSG" => "1 datastore mount(s) ok",
    "NHC_LIBVIRT" => "OK",
    "NHC_LIBVIRT_MSG" => "libvirt ok (0 domain(s))"
  }.freeze

  def payload(overrides = {})
    {
      message: "host=node01 id=0 status=CRIT action=disable (notify): CRIT 1/1",
      host: "node01",
      host_id: 0,
      status: "CRIT",
      action: "disable",
      applied: false,
      time: "2026-11-17T20:00:00Z",
      sample: 1_794_942_477,
      details: DETAILS
    }.merge(overrides)
  end

  def test_html_contains_the_summary_and_checks
    html = OneNHC::EmailTemplate.html(payload)

    assert_includes html, "Host health alert"
    assert_includes html, "node01"
    assert_includes html, "CRIT"
    assert_includes html, "disable"
    assert_includes html, "3 checks"
    assert_includes html, "1 crit"
    assert_includes html, "Checks"
    assert_includes html, "fs-ro"
    assert_includes html, "read-only: /data (ext4)"
    assert_includes html, "datastore-mounts"
    assert_includes html, "libvirt"
    assert_includes html, "2026-11-17 20:00:00 UTC"
  end

  def test_text_contains_the_summary_and_checks
    text = OneNHC::EmailTemplate.text(payload)

    assert_includes text, "one-nhc host health alert"
    assert_includes text, "Host:    node01 (id 0)"
    assert_includes text, "Summary: 3 checks · 1 crit · 0 warn · 2 ok"
    assert_includes text, "Checks:"
    assert_includes text, "CRIT   fs-ro"
    assert_includes text, "read-only: /data (ext4)"
    assert_includes text, "Generated by one-nhc"
  end

  def test_html_escapes_dynamic_values
    html = OneNHC::EmailTemplate.html(
      payload(
        message: "<script>alert('x')</script>",
        details: DETAILS.merge("NHC_FS_RO_MSG" => "<b>read-only</b>")
      )
    )

    refute_includes html, "<script>alert"
    assert_includes html, "&lt;script&gt;alert"
    assert_includes html, "&lt;b&gt;read-only&lt;/b&gt;"
  end

  def test_html_omits_the_checks_section_without_details
    html = OneNHC::EmailTemplate.html(payload(details: {}))

    refute_includes html, ">Checks<"
    refute_includes html, "fs-ro"
  end

  def test_html_shows_probe_errors
    html = OneNHC::EmailTemplate.html(
      payload(details: DETAILS.merge("NHC_ERROR" => "probe failed"))
    )

    assert_includes html, "Probe error: probe failed"
  end

  def test_html_uses_a_colour_for_the_status
    assert_includes OneNHC::EmailTemplate.html(payload(status: "CRIT")), "#ef4444"
    assert_includes OneNHC::EmailTemplate.html(payload(status: "OK")), "#22c55e"
    assert_includes OneNHC::EmailTemplate.html(payload(status: "WARN")), "#f59e0b"
  end

  def test_applied_is_rendered_as_yes_or_no
    assert_includes OneNHC::EmailTemplate.text(payload(applied: true)), "Applied: yes"
    assert_includes OneNHC::EmailTemplate.text(payload(applied: false)), "Applied: no"
  end
end
