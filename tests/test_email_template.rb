# frozen_string_literal: true

require_relative "test_helper"

class TestEmailTemplate < Minitest::Test
  DETAILS = {
    "NHC_STATUS" => "CRIT",
    "NHC_CHECK_COUNT" => "3",
    "NHC_CRIT" => "1",
    "NHC_WARN" => "0",
    "NHC_OK" => "2",
    "NHC_SKIP" => "0",
    "NHC_UNKNOWN" => "0",
    "NHC_FS_RO" => "CRIT",
    "NHC_FS_RO_MSG" => "read-only: /data (ext4)",
    "NHC_DATASTORE_MOUNTS" => "OK",
    "NHC_DATASTORE_MOUNTS_MSG" => "1 datastore mount(s) ok",
    "NHC_LIBVIRT" => "OK",
    "NHC_LIBVIRT_MSG" => "libvirt ok (0 domain(s))"
  }.freeze

  CHECK_TAGS = {
    "fs-ro" => ["storage"],
    "datastore-mounts" => ["storage"],
    "libvirt" => ["compute"],
    "fs-usage" => ["storage"],
    "network-interface" => ["network"],
    "infiniband" => %w[network hardware],
    "service" => ["services"],
    "raid" => %w[storage hardware],
    "smart" => %w[storage hardware],
    "gpu" => %w[hardware gpu],
    "gpu-fabric" => %w[hardware gpu],
    "ofed-version" => %w[network hardware]
  }.freeze

  ALL_DETAILS = {
    "NHC_STATUS" => "CRIT",
    "NHC_CHECK_COUNT" => "12",
    "NHC_CRIT" => "1",
    "NHC_WARN" => "0",
    "NHC_OK" => "11",
    "NHC_SKIP" => "0",
    "NHC_UNKNOWN" => "0",
    "NHC_FS_RO" => "OK",
    "NHC_FS_RO_MSG" => "all real filesystems are read-write",
    "NHC_DATASTORE_MOUNTS" => "OK",
    "NHC_DATASTORE_MOUNTS_MSG" => "2 datastore mount(s) ok",
    "NHC_LIBVIRT" => "OK",
    "NHC_LIBVIRT_MSG" => "libvirt ok (4 domain(s))",
    "NHC_FS_USAGE" => "OK",
    "NHC_FS_USAGE_MSG" => "2 filesystem(s) ok",
    "NHC_NETWORK_INTERFACE" => "OK",
    "NHC_NETWORK_INTERFACE_MSG" => "3 interface(s) up",
    "NHC_INFINIBAND" => "CRIT",
    "NHC_INFINIBAND_MSG" => "mlx5_0/1 state DOWN (expected ACTIVE)",
    "NHC_SERVICE" => "OK",
    "NHC_SERVICE_MSG" => "2 service(s) active",
    "NHC_RAID" => "OK",
    "NHC_RAID_MSG" => "1 RAID array(s) healthy",
    "NHC_SMART" => "OK",
    "NHC_SMART_MSG" => "2 disk(s) SMART healthy",
    "NHC_GPU" => "OK",
    "NHC_GPU_MSG" => "4 GPU(s) present",
    "NHC_GPU_FABRIC" => "OK",
    "NHC_GPU_FABRIC_MSG" => "4 GPU(s) Fabric healthy",
    "NHC_OFED_VERSION" => "OK",
    "NHC_OFED_VERSION_MSG" => "mlnx-ofa_kernel version 26.01"
  }.freeze

  def payload(overrides = {})
    {
      message: "host=node01 id=0 status=CRIT action=disable (notify): CRIT 1/1",
      host: "node01",
      host_id: 0,
      cluster: "default",
      status: "CRIT",
      action: "disable",
      applied: false,
      time: "2026-11-17T20:00:00Z",
      sample: 1_794_942_477,
      details: DETAILS,
      check_tags: CHECK_TAGS
    }.merge(overrides)
  end

  def test_html_contains_the_summary_and_checks
    html = OneNHC::EmailTemplate.html(payload)

    assert_includes html, "Host health alert"
    assert_includes html, "node01"
    assert_includes html, "Cluster"
    assert_includes html, "CRIT"
    assert_includes html, "disable"
    assert_includes html, "3 checks"
    assert_includes html, "1 crit"
    assert_includes html, "Checks"
    assert_includes html, "fs-ro"
    assert_includes html, "read-only: /data (ext4)"
    assert_includes html, "datastore-mounts"
    assert_includes html, "libvirt"
    assert_includes html, "2026-11-17 20:00:00 UTC"
  end

  def test_text_contains_the_summary_and_checks
    text = OneNHC::EmailTemplate.text(payload)

    assert_includes text, "one-nhc host health alert"
    assert_includes text, "Host:    node01 (id 0)"
    assert_includes text, "Cluster: default"
    assert_includes text, "Summary: 3 checks · 1 crit · 0 warn · 2 ok"
    assert_includes text, "Checks:"
    assert_includes text, "CRIT   fs-ro"
    assert_includes text, "read-only: /data (ext4)"
    assert_includes text, "Generated by one-nhc"
  end

  def test_html_escapes_dynamic_values
    html = OneNHC::EmailTemplate.html(
      payload(
        message: "<script>alert('x')</script>",
        details: DETAILS.merge("NHC_FS_RO_MSG" => "<b>read-only</b>")
      )
    )

    refute_includes html, "<script>alert"
    assert_includes html, "&lt;script&gt;alert"
    assert_includes html, "&lt;b&gt;read-only&lt;/b&gt;"
  end

  def test_html_omits_the_checks_section_without_details
    html = OneNHC::EmailTemplate.html(payload(details: {}))

    refute_includes html, ">Checks<"
    refute_includes html, "fs-ro"
  end

  def test_html_shows_probe_errors
    html = OneNHC::EmailTemplate.html(
      payload(details: DETAILS.merge("NHC_ERROR" => "probe failed"))
    )

    assert_includes html, "Probe error: probe failed"
  end

  def test_html_uses_a_colour_for_the_status
    assert_includes OneNHC::EmailTemplate.html(payload(status: "CRIT")), "#ef4444"
    assert_includes OneNHC::EmailTemplate.html(payload(status: "OK")), "#22c55e"
    assert_includes OneNHC::EmailTemplate.html(payload(status: "WARN")), "#f59e0b"
  end

  def test_applied_is_rendered_as_yes_or_no
    assert_includes OneNHC::EmailTemplate.text(payload(applied: true)), "Applied: yes"
    assert_includes OneNHC::EmailTemplate.text(payload(applied: false)), "Applied: no"
  end

  def test_warn_action_label
    text = OneNHC::EmailTemplate.text(payload(status: "WARN", action: "warn"))
    assert_includes text, "Health warning"
  end

  def test_grouped_html_has_sections_and_failures_first
    html = OneNHC::EmailTemplate.html(
      payload(details: ALL_DETAILS), group_by: "tags", failures_first: true
    )

    assert_includes html, "Compute"
    assert_includes html, "Storage"
    assert_includes html, "Network"
    assert_includes html, "Services"
    assert_includes html, "Network 2/3"
    assert_includes html, "infiniband"
    assert_includes html, "ofed-version"
    assert_includes html, "mlx5_0/1 state DOWN (expected ACTIVE)"

    assert_operator html.index("Network"), :<, html.index("infiniband")
    assert_operator html.index("infiniband"), :<, html.index("network-interface")
  end

  def test_grouped_text_has_sections
    text = OneNHC::EmailTemplate.text(
      payload(details: ALL_DETAILS), group_by: "tags", failures_first: true
    )

    assert_includes text, "Groups:  Compute 3/3"
    assert_includes text, "Storage 5/5"
    assert_includes text, "Network 2/3"
    assert_includes text, "Network:"
    assert_includes text, "infiniband"
    assert_includes text, "ofed-version"
  end

  def test_group_by_none_keeps_the_flat_table
    html = OneNHC::EmailTemplate.html(payload(details: ALL_DETAILS))

    assert_includes html, ">Checks<"
    refute_includes html, ">Compute<"
  end

  def test_failures_first_works_without_groups
    html = OneNHC::EmailTemplate.html(
      payload(details: ALL_DETAILS), failures_first: true
    )

    assert_operator html.index("infiniband"), :<, html.index("datastore-mounts")
  end

  def test_decision_message_is_above_the_checks
    html = OneNHC::EmailTemplate.html(payload(message: "UNIQUE-DECISION-MESSAGE"))
    text = OneNHC::EmailTemplate.text(payload(message: "UNIQUE-DECISION-MESSAGE"))

    assert_operator html.index("UNIQUE-DECISION-MESSAGE"), :<, html.index(">Checks<")
    assert_operator text.index("UNIQUE-DECISION-MESSAGE"), :<, text.index("Summary:")
  end
end
